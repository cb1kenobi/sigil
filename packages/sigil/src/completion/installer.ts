/**
 * Putting a completion script where the shell will find it.
 *
 * `./install.ts` is the table of *where* a completion goes, machine-independent
 * because it goes into a script's own header. This is the half that resolves
 * that table against this machine, reads what is already there, and writes --
 * which is why the file system is in here and not there.
 *
 * ## It writes the file and prints the rc line
 *
 * The file is the part with no downside: a directory and a file of our own,
 * under the user's own data home, created if absent. The *startup file* is not
 * touched, and that is the decision rather than an omission -- a `.zshrc` is
 * very often under version control, is routinely generated by a dotfile
 * manager, and is the one file whose contents the user has an opinion about.
 * Appending to one is also the half that cannot be undone safely: a line we
 * added and a line they added look identical afterwards, so an uninstall would
 * have to edit a file it did not write. So: the line is **printed**, the
 * installer reads the startup file to find out whether it is already there, and
 * where the route needs no line at all -- `bash-completion`'s own user
 * directory -- there is nothing left to print and the install is complete.
 *
 * ## `writeAtomic()` rather than `writeFileSync()`
 *
 * Every axis that function exists for applies here. A completion script is a
 * file a shell *sources*, so half of one is a syntax error in somebody's
 * startup. People check completions into a dotfiles repository, so the path may
 * be a **symlink** -- and replacing a link with a plain file is the defect that
 * module was fixed for twice, once for a resolved link and once for a dangling
 * one. `sudo app completion` must not leave a root-owned file in somebody's
 * home, which is its chown pass. And a file somebody has `chmod`-ed stays as
 * they left it. So this is a second *caller* rather than a second writer, and
 * the directory comes free: `writeAtomic()` calls `mkdirOwnerSync()` itself.
 *
 * ## The marker is what makes re-running safe
 *
 * `sigil add`'s discipline is to print the plan and refuse to overwrite a file
 * somebody edited without `--force`. A completion script is *generated output*
 * that changes whenever the app's commands do, so refusing to update one would
 * be refusing the ordinary case -- and we have what `add` does not: a marker we
 * wrote. So a file carrying `generatedBy()` is ours and is replaced freely, a
 * file whose bytes already match is left alone and reported as such, and
 * anything else is somebody's work and is refused.
 */

import { isMissing, writeAtomic } from '../config/atomic.js';
import { __ } from '../i18n/index.js';
import { baseDir, expand, home } from '../paths.js';
import { generatedBy, installHint, shQuote, type RouteId } from './install.js';
import type { ShellName } from './shells.js';
import { accessSync, constants, readFileSync, statSync, unlinkSync } from 'node:fs';
import { basename, join } from 'node:path';

/** Which way round the plan is being read. */
export type Action = 'install' | 'uninstall';

/** What a route needs added to a startup file. */
export interface RcAddition {
  /** The startup file, absolute. */
  readonly file: string;
  /** The line, ready to paste. */
  readonly line: string;
  /**
   * The path the line names, unquoted.
   *
   * What the idempotency check looks for, rather than the line itself: a user
   * who added it by hand may have written it with double quotes, with none, or
   * as part of a longer line, and all three mean it is handled. The path is the
   * granularity a human would check at, and the only thing this decides is
   * whether to *print* -- so reading a mention inside a comment as "already
   * there" is the safe direction. It is also what makes the second sigil app
   * you install say "nothing to add" on zsh, because the `fpath` line names the
   * directory every one of them writes into.
   */
  readonly needle: string;
  /** Where in the file it has to go, where that matters. */
  readonly where?: string;
}

/** A place this process can write a completion script to. */
export interface InstallTarget {
  /** The directory holding it. */
  readonly dir: string;
  /** The script, absolute. */
  readonly file: string;
  /** The route this came from. */
  readonly id: RouteId;
  /** What the route's label said, for the plan. */
  readonly label: string;
  /** What has to be added to a startup file, where anything does. */
  readonly rc?: RcAddition;
  /** The shell it is for. */
  readonly shell: ShellName;
}

/** What is at the target already. */
export type FileState =
  /** Nothing there. */
  | 'create'
  /** Ours, and already byte for byte what would be written. */
  | 'current'
  /** There, and not ours. */
  | 'foreign'
  /** Ours, and out of date. */
  | 'update';

/** Whether the startup file already names the path. */
export type RcState =
  /** The route needs no line. */
  | 'none'
  /** It needs one and the file does not name the path. */
  | 'absent'
  /** It needs one and the file names the path already. */
  | 'present';

/** What installing or uninstalling would do. */
export interface InstallPlan {
  /**
   * Whether anything at all is outstanding, the printed line included.
   *
   * What decides "nothing to do". It is wider than `writes` on purpose: a
   * script that is already current and a startup file that never got its line
   * is not nothing to do, and reporting it as such is how somebody comes to
   * have a completion installed that their shell never loads.
   */
  readonly changes: boolean;
  /**
   * What is at the script's path.
   *
   * For an uninstall the four states collapse to three and are read one step
   * along: `create` is "there is nothing to remove", `update` is "ours, and it
   * will go", and `foreign` is "somebody else's, and it will not". `current`
   * never arises, because an uninstall has no script to compare against.
   */
  readonly file: FileState;
  /** Whether the startup file names it. */
  readonly rc: RcState;
  /** Where it goes. */
  readonly target: InstallTarget;
  /**
   * Whether there is a file to write or remove.
   *
   * What decides whether to **ask**, which is not the same question as
   * `changes`: where the only thing outstanding is the line this prints rather
   * than writes, a confirm would be asking permission to do nothing -- and then
   * answering yes and being told "nothing to do", which is what it did for one
   * commit. Found by driving the command rather than by a test.
   */
  readonly writes: boolean;
}

/**
 * The home directory, which `paths.home()` types as optional and `homedir()`
 * never answers nothing for.
 *
 * The cast is the type being wider than the function: `home()` is
 * `string | undefined` because its `join()` branch is, and `homedir()` answers
 * a string on every platform. A guard here would be code nothing can reach,
 * which this repository deletes rather than keeps, and a `??` fallback would be
 * inventing a second answer for a case that does not arise.
 *
 * @returns The home directory.
 */
function homeDir(): string {
  return home() as string;
}

/**
 * The data home every directory of ours hangs off.
 *
 * `XDG_DATA_HOME` through `baseDir()` -- expanded, then required absolute,
 * which is the rule the spec states and the one `paths.ts` records -- else
 * `~/.local/share`, which is `bash-completion`'s own fallback and so is the
 * answer on every platform. `paths.data()` is deliberately not it: see
 * `SHOWN_BASE` in `./install.ts` for why.
 *
 * @param env - The environment to read.
 * @returns The base, absolute.
 */
function dataHome(env: Record<string, string | undefined>): string {
  return baseDir(env['XDG_DATA_HOME']) ?? expand('~/.local/share');
}

/**
 * The first of these startup files that is a file, or the first regardless.
 *
 * `.bashrc` first, because that is where a completion conventionally goes and
 * what an interactive bash reads. macOS starts bash as a *login* shell, which
 * reads `.bash_profile` and not `.bashrc` -- so where `.bashrc` is absent and
 * `.bash_profile` is there, naming the second is the only answer a shell will
 * act on, and that is what this is for.
 *
 * What it does **not** claim is that the order is right on macOS when *both*
 * exist: there it names `.bashrc`, which a login shell reads only if
 * `.bash_profile` sources it -- which is the ordinary arrangement and is not
 * guaranteed. The alternative is reading somebody's `.bash_profile` to find out
 * whether it sources the other, which is parsing a dotfile to decide a
 * suggestion, so the order stands and the wrinkle is written down. The first
 * version of this comment gave the login-shell argument as the *reason* for the
 * order, which on its own terms says `.bash_profile` should win -- a reader was
 * told a false reason for defensible code. Found by review.
 *
 * @param candidates - Absolute paths, most conventional first.
 * @returns One of them.
 */
function firstExisting(candidates: readonly [string, ...string[]]): string {
  for (const path of candidates) {
    try {
      if (statSync(path).isFile()) {
        return path;
      }
    } catch {
      // a candidate this cannot stat is one the shell may still read, and the
      // next one is the better guess. Where every candidate refuses, the
      // fallback below names the conventional one, which is what a reader can
      // act on -- there is nothing to report here, because naming a startup
      // file is a suggestion rather than an operation
    }
  }

  return candidates[0];
}

/**
 * Where this process could write a completion script for `shell`.
 *
 * Resolved from the same routes `installHint()` prints, by walking that table
 * rather than looking an id up in it -- so the label comes from the route being
 * resolved, a route taken out of the table simply stops producing a target, and
 * there is no fallback for a lookup that missed. The routes only a shell or
 * root can take resolve to nothing and are not in the answer, which is why this
 * is a list: what a human can do is a wider set than what this can.
 *
 * In the table's own order, most automatic first. For bash that means
 * `bash-completion`'s user directory when it is there, because it needs nothing
 * added to a startup file.
 *
 * @param shell - The shell.
 * @param program - The program's name, as the user types it.
 * @param env - The environment, for `XDG_DATA_HOME` and `ZDOTDIR`.
 * @returns The targets, best first. Never empty: the `user` route always
 *   resolves, which is what makes it the fallback.
 */
export function installTargets(
  shell: ShellName,
  program: string,
  env: Record<string, string | undefined>
): readonly InstallTarget[] {
  // the one reader of `program` that turns it into a *path*, so the one that
  // has to ask whether it is a path segment. `completionSpec()` refuses a name
  // with whitespace in it or a leading dash, because those are what a shell
  // cannot register -- and lets a separator through, because a shell does not
  // care. Measured: `name: '../../../evil'` wrote `<data home>/evil`, one
  // directory up and out of the completions directory, with `writeAtomic()`
  // creating whatever chain it landed in. Found by review.
  //
  // English, because `schema.name` is the app author's own: it is a bug report
  // in their code rather than anything a user did
  if (program === '' || program !== basename(program) || program === '.' || program === '..') {
    throw new Error(
      `Expected the program name to be one path segment, not "${program}": a completion script is a file named after it.`
    );
  }

  const base = dataHome(env);
  const ours = join(base, 'completions');
  const out: InstallTarget[] = [];

  for (const route of installHint(shell, program).routes) {
    const target = resolveRoute(route.id, shell, program, base, ours, env);
    if (target !== undefined) {
      out.push({ ...target, id: route.id, label: route.label, shell });
    }
  }

  return out;
}

/** The resolved half of a target, before the route's own fields go on it. */
type Resolved = Omit<InstallTarget, 'id' | 'label' | 'shell'>;

/**
 * One route resolved against this machine, or nothing where it cannot be.
 *
 * @param id - Which route.
 * @param shell - The shell.
 * @param program - The program's name.
 * @param base - The data home.
 * @param ours - Our own completions directory.
 * @param env - The environment.
 * @returns The paths, or nothing.
 */
function resolveRoute(
  id: RouteId,
  shell: ShellName,
  program: string,
  base: string,
  ours: string,
  env: Record<string, string | undefined>
): Resolved | undefined {
  if (id === 'user') {
    if (shell === 'zsh') {
      // `ZDOTDIR` through `baseDir()` too, because a relative one is not a
      // directory zsh would read either -- one rule for every base this reads
      const zdot = baseDir(env['ZDOTDIR']) ?? homeDir();
      return {
        dir: ours,
        file: join(ours, `_${program}`),
        rc: {
          file: join(zdot, '.zshrc'),
          line: `fpath=(${shQuote(ours)} $fpath)`,
          needle: ours,
          where: 'above your compinit line',
        },
      };
    }

    const file = join(ours, `${program}.bash`);
    return {
      dir: ours,
      file,
      rc: {
        file: firstExisting([
          join(homeDir(), '.bashrc'),
          join(homeDir(), '.bash_profile'),
          join(homeDir(), '.profile'),
        ]),
        line: `source ${shQuote(file)}`,
        needle: file,
      },
    };
  }

  if (id === 'bash-completion') {
    // only where the directory is already there, and that gate is the whole of
    // what stands in for a version check. `BASH_COMPLETION_VERSINFO` is set
    // inside a bash that loaded bash-completion and reaches no environment this
    // process has, so there is nothing to read -- and the directory existing is
    // evidence that something installed a user completion into it, which a
    // bash-completion older than 2.8 would not have done: that one read
    // `~/.bash_completion.d` instead and never creates this one. Where it is
    // absent the `user` route works on any bash, which is the safe direction --
    // and it is the one verified in a real bash 3.2 here, where this one is a
    // claim only a machine with bash-completion on it can settle. See
    // `scripts/terminal-probe.mjs --completion`
    const dir = join(base, 'bash-completion', 'completions');
    try {
      if (!statSync(dir).isDirectory()) {
        return undefined;
      }

      // and writable, which is the half the existence check alone got wrong:
      // the directory may be root-owned from a system install, on a read-only
      // mount, or somebody else's on a shared machine -- and then `writeAtomic()`
      // throws a raw `EACCES` while the `user` route, which works on any bash,
      // sits unused at the next index. Nothing retries, so the check has to be
      // here. A race remains -- writable when asked and not when written -- and
      // that is the file system's rather than a gate's. Found by review
      accessSync(dir, constants.W_OK);
    } catch {
      return undefined;
    }

    return { dir, file: join(dir, program) };
  }

  // `fpath`, `system` and `eval` are a shell's or root's, which is what the
  // `RouteId` doc means by a list rather than one target per route
  return undefined;
}

/**
 * What a path holds, or nothing where there is nothing there.
 *
 * Only `ENOENT` is nothing, which is `isMissing()`'s own rule: a path that
 * names a *directory* is `EISDIR` and is somebody pointing at the wrong thing,
 * and answering "there is no completion script" for it is the silence that
 * costs an afternoon.
 *
 * @param path - The file.
 * @returns Its contents, or nothing.
 * @throws If the read failed for any reason but the file not being there.
 */
function readOr(path: string): string | undefined {
  try {
    return readFileSync(path, 'utf8');
  } catch (e: unknown) {
    if (isMissing(e)) {
      return undefined;
    }

    // translated, because what provokes it is a *user's* own home directory: an
    // unreadable startup file, a directory where a script should be, a
    // permission they set. The key is the one the config stores already throw,
    // so this costs none -- and without it the one place that throws a file
    // system error from inside an otherwise fully translated interaction showed
    // translated prompts and then node's English
    throw new Error(__`Failed to read ${path}: ${(e as Error).message}`);
  }
}

/**
 * Every spelling of one path that counts as the startup file naming it.
 *
 * The absolute path, and the two home-relative forms. Which matters because the
 * `~` one is **our own output**: `installComment()` writes the routes into every
 * generated script's header and `instructions()` prints them when there is
 * nobody to ask, both as `~/.local/share/completions` -- so a user who set
 * completion up by following this package's own recipe, which before SIG-151
 * was the only way there was, has a `~` in their `.zshrc`. An absolute-only
 * needle finds nothing there and reports `absent` for ever: the line is
 * reprinted on every run and "nothing to do" is unreachable for exactly the
 * population that did what they were told. Found by review.
 *
 * `$HOME/` beside it because a shell writer who did not want the tilde wrote
 * that, and both are the same directory. Derived from the one path rather than
 * listed, so there is nothing to keep in agreement.
 *
 * @param path - The path, absolute.
 * @returns The spellings, longest first so a substring search is unambiguous.
 */
function spellings(path: string): readonly string[] {
  const dir = homeDir();

  if (!path.startsWith(dir)) {
    return [path];
  }

  const rest = path.slice(dir.length);

  return [path, `~${rest}`, `$HOME${rest}`];
}

/**
 * Whether the startup file already names the path the line would add.
 *
 * @param rc - The addition, or nothing where the route needs none.
 * @returns What there is to do about it.
 */
function rcStateOf(rc: RcAddition | undefined): RcState {
  if (rc === undefined) {
    return 'none';
  }

  const held = readOr(rc.file);
  if (held === undefined) {
    return 'absent';
  }

  return spellings(rc.needle).some((spelling) => held.includes(spelling)) ? 'present' : 'absent';
}

/**
 * What installing would do, read off the file system.
 *
 * @param target - Where it goes.
 * @param script - What would be written.
 * @param program - The program's name, for the marker.
 * @returns The plan.
 */
/**
 * Whether a file is one of ours, read off its **header**.
 *
 * The marker is a sentence, and a sentence is something any file can contain --
 * a note quoting it, a wrapper that embeds a generated script, a README pasted
 * into the wrong place. Both emitters put it on the first or second line, so
 * that is where it is looked for: a file that merely mentions it fifty lines
 * down is somebody's work and is refused. Found by review, which had
 * `planUninstall()` **unlinking** such a file after one default-yes confirm.
 *
 * Three lines rather than two, because the zsh header is `#compdef` and then
 * the marker, and one more is slack for a header that grows a line.
 *
 * @param held - What the file holds.
 * @param shell - The shell its path is for.
 * @param program - The program's name.
 * @returns Whether this is generated output rather than somebody's file.
 */
function ours(held: string, shell: ShellName, program: string): boolean {
  return held.split('\n', HEADER_LINES).join('\n').includes(generatedBy(shell, program));
}

/** How far into a file the marker has to be for the file to be ours. */
const HEADER_LINES = 3;

export function planInstall(target: InstallTarget, script: string, program: string): InstallPlan {
  const held = readOr(target.file);

  let file: FileState;
  if (held === undefined) {
    file = 'create';
  } else if (!ours(held, target.shell, program)) {
    file = 'foreign';
  } else if (held === script) {
    file = 'current';
  } else {
    file = 'update';
  }

  const rc = rcStateOf(target.rc);
  const writes = file !== 'current';

  return { changes: writes || rc === 'absent', file, rc, target, writes };
}

/**
 * What uninstalling would do.
 *
 * The same marker, which is what keeps this from deleting a file somebody else
 * put at our path. It is refused **outright** rather than offered, which is the
 * one place the two directions differ: replacing a generated path is the
 * ordinary upgrade case and is worth asking about, where deleting a stranger's
 * file gains nothing a `rm` would not -- the plan names the path and says it is
 * not ours, which is what a reader needs. So `changes` is false for one and the
 * question below never reaches it.
 *
 * There is no script to compare against, so `current` cannot arise and `update`
 * means "ours, and it will go" -- which is what `InstallPlan.file` says of the
 * uninstall reading.
 *
 * @param target - Where it was.
 * @param program - The program's name, for the marker.
 * @returns The plan.
 */
export function planUninstall(target: InstallTarget, program: string): InstallPlan {
  const held = readOr(target.file);

  let file: FileState;
  if (held === undefined) {
    file = 'create';
  } else if (ours(held, target.shell, program)) {
    file = 'update';
  } else {
    file = 'foreign';
  }

  // a `foreign` file is refused outright rather than offered, so it is nothing
  // to ask about -- which is where the install's two booleans part company
  const writes = file === 'update';
  const rc = rcStateOf(target.rc);

  // and the line counts, which it did not for one commit: a script somebody
  // already removed by hand with the line still in their `.zshrc` is not
  // nothing to do, and saying so while `resultLines()` printed "Remove this
  // line from ..." in the same breath was the interface's own contract -- "what
  // decides nothing to do, the printed line included" -- disagreeing with one
  // of its two constructors. Found by review
  return { changes: writes || rc === 'present', file, rc, target, writes };
}

/**
 * Writes the script, unless it is already there byte for byte.
 *
 * The `current` case is skipped rather than written over, and that is not
 * tidiness: it is what keeps a re-run from touching the mtime of a file nothing
 * about which has changed, which is what a watcher or a `make` rule reads.
 *
 * @param plan - What to do, from `planInstall()`.
 * @param script - What to write.
 * @returns Whether anything was written.
 */
export async function applyInstall(
  plan: InstallPlan,
  script: string,
  opts: { replace?: boolean } = {}
): Promise<boolean> {
  if (plan.file === 'current') {
    return false;
  }

  // the module whose job is the writing enforces its own rule rather than
  // leaving it to one caller's discipline. `planInstall()` says whose the file
  // is and `interactive.ts` asks about it; handed a `foreign` plan with no
  // answer this used to write, so the refusal was a property of the command
  // rather than of the writer. `replace` is what the answer looks like from
  // here, so a caller that forgot to ask gets a throw rather than a destroyed
  // file. English, because only a caller's own code can provoke it
  if (plan.file === 'foreign' && opts.replace !== true) {
    throw new Error(
      `Refusing to replace ${plan.target.file}, which sigil did not write: ask first, then pass { replace: true }.`
    );
  }

  await writeAtomic(plan.target.file, script);
  return true;
}

/**
 * Removes the script.
 *
 * @param plan - What to do, from `planUninstall()`.
 * @returns Whether anything was removed.
 */
export function applyUninstall(plan: InstallPlan): boolean {
  if (plan.file === 'create') {
    return false;
  }

  // and here there is no opt-in at all, which is the asymmetry `planUninstall()`
  // records: replacing a generated path is the ordinary upgrade case and is
  // worth asking about, where deleting a stranger's file gains nothing a `rm`
  // would not. A caller cannot ask its way past this one
  if (plan.file === 'foreign') {
    throw new Error(`Refusing to remove ${plan.target.file}, which sigil did not write.`);
  }

  unlinkSync(plan.target.file);
  return true;
}

/**
 * The plan, as the lines to show before asking.
 *
 * Rendered here rather than in the command, because the one line that is not a
 * path is the `where` clause -- "above your compinit line" -- and that is a
 * fact about zsh. A translator wants whole sentences rather than a fragment
 * through a slot, which is the rule the suggestion work records, so the clause
 * is inside the key and the key is chosen by the shell. That choice belongs
 * where the shell knowledge already is.
 *
 * @param plan - What would happen.
 * @param action - Which way round.
 * @returns The lines, each already indented, with no trailing newline.
 */
export function planLines(plan: InstallPlan, action: Action): string[] {
  const out: string[] = [];
  const { file } = plan.target;

  // `foreign` first, because it is the one state where the *verb* would lie:
  // "it will replace" over a file somebody wrote reads as a decision already
  // taken, and the plan is what a reader sees before the question. Found by the
  // end-to-end test rather than by reading, which is the half a unit test of
  // the plan could not see -- it asserted the state and not the sentence
  if (plan.file === 'foreign') {
    out.push(__`${file} was not written by sigil`);
  } else if (action === 'uninstall') {
    out.push(plan.file === 'create' ? __`${file} is not there` : __`It will remove ${file}`);
  } else if (plan.file === 'current') {
    out.push(__`${file} is already up to date`);
  } else if (plan.file === 'create') {
    out.push(__`It will write ${file}`);
  } else {
    out.push(__`It will replace ${file}`);
  }

  // narrowed rather than read through a `?? ''`, which would be a fallback for
  // a state that cannot arise: `rcStateOf()` answers `none` for a route with no
  // line, so an `absent` or a `present` is a route that has one
  const { rc } = plan.target;
  if (rc !== undefined) {
    if (plan.rc === 'absent' && action === 'install') {
      out.push(__`A line has to go in ${rc.file}`);
    } else if (plan.rc === 'present') {
      out.push(__`${rc.file} already names it`);
    }
  }

  return out.map((line) => `  ${line}`);
}

/**
 * What to say once it is done.
 *
 * The rc line is printed here and nowhere else, which is the whole of "write
 * the file, print the line": there is no path through this module that appends
 * to a startup file, so a reader can check that by reading one function.
 *
 * @param plan - What was done.
 * @param action - Which way round.
 * @param did - Whether the file was actually written or removed.
 * @returns The lines, with no trailing newline.
 */
export function resultLines(plan: InstallPlan, action: Action, did: boolean): string[] {
  const out: string[] = [];
  const { file, rc, shell } = plan.target;

  if (action === 'uninstall') {
    if (did) {
      out.push(__`Removed ${file}`);
    } else if (!plan.changes) {
      out.push(__`Nothing to do.`);
    }

    // the line is left for the reader, because this never added one: a line we
    // appended and a line they wrote are the same bytes afterwards, so editing
    // it back out would be editing a file this did not write
    if (rc !== undefined && plan.rc === 'present') {
      out.push('', __`Remove this line from ${rc.file}:`, '', `    ${rc.line}`);
    }

    return out;
  }

  if (did) {
    out.push(__`Wrote ${file}`);
  } else if (!plan.changes) {
    // nothing at all outstanding, which is the re-run this has to say so for
    out.push(__`Nothing to do.`);
  }
  // and where nothing was written but something *is* outstanding -- a script
  // that is already right and a startup file that never got its line -- the
  // first line is left out rather than repeated: the plan above has just said
  // it is up to date, and "Nothing to do." there is simply false. Both
  // spellings shipped for a commit each, and driving the command is what found
  // them

  if (rc !== undefined && plan.rc === 'absent') {
    out.push(
      '',
      shell === 'zsh'
        ? __`Add this line to ${rc.file}, above your compinit line:`
        : __`Add this line to ${rc.file}:`,
      '',
      `    ${rc.line}`,
      '',
      __`Then restart your shell.`
    );
  } else if (did) {
    // nothing to add, which is `bash-completion`'s own user directory and the
    // one route that is fully automatic -- so the only thing left is the shell
    // not having read it yet
    out.push('', __`Then restart your shell.`);
  }

  return out;
}
