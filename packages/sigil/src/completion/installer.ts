/**
 * Putting a completion script where the shell will find it.
 *
 * `./install.ts` is the table of *where* a completion goes, machine-independent
 * because it goes into a script's own header. This is the half that resolves
 * that table against this machine, reads what is already there, and writes --
 * which is why the file system is in here and not there.
 *
 * ## It writes the file and prints the rc line
 *
 * The file is the part with no downside: a directory and a file of our own,
 * under the user's own data home, created if absent. The *startup file* is not
 * touched, and that is the decision rather than an omission -- a `.zshrc` is
 * very often under version control, is routinely generated by a dotfile
 * manager, and is the one file whose contents the user has an opinion about.
 * Appending to one is also the half that cannot be undone safely: a line we
 * added and a line they added look identical afterwards, so an uninstall would
 * have to edit a file it did not write. So: the line is **printed**, the
 * installer reads the startup file to find out whether it is already there, and
 * where the route needs no line at all -- `bash-completion`'s own user
 * directory -- there is nothing left to print and the install is complete.
 *
 * ## `writeAtomic()` rather than `writeFileSync()`
 *
 * Every axis that function exists for applies here. A completion script is a
 * file a shell *sources*, so half of one is a syntax error in somebody's
 * startup. People check completions into a dotfiles repository, so the path may
 * be a **symlink** -- and replacing a link with a plain file is the defect that
 * module was fixed for twice, once for a resolved link and once for a dangling
 * one. `sudo app completion` must not leave a root-owned file in somebody's
 * home, which is its chown pass. And a file somebody has `chmod`-ed stays as
 * they left it. So this is a second *caller* rather than a second writer, and
 * the directory comes free: `writeAtomic()` calls `mkdirOwnerSync()` itself.
 *
 * ## The marker is what makes re-running safe
 *
 * `sigil add`'s discipline is to print the plan and refuse to overwrite a file
 * somebody edited without `--force`. A completion script is *generated output*
 * that changes whenever the app's commands do, so refusing to update one would
 * be refusing the ordinary case -- and we have what `add` does not: a marker we
 * wrote. So a file carrying `generatedBy()` is ours and is replaced freely, a
 * file whose bytes already match is left alone and reported as such, and
 * anything else is somebody's work and is refused.
 */

