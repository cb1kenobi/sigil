#!/usr/bin/env node
/**
 * Regenerates `src/width/east-asian-width.ts` from the Unicode Character
 * Database.
 *
 * East Asian Width is the one thing display width needs that the runtime will
 * not tell us. `Intl.Segmenter` handles grapheme clustering and the `\p{...}`
 * property escapes cover the categories that make a character zero width, but
 * there is no `\p{East_Asian_Width=W}` in ECMAScript and `util.getStringWidth`
 * is internal to Node. So the ranges are generated here and committed, which is
 * also what keeps the library at zero dependencies.
 *
 * Run it when a new Unicode version lands, with the version to move to:
 *
 *     node scripts/generate-east-asian-width.mjs 18.0.0
 *
 * The version is pinned rather than tracking `latest`, so that re-running this
 * reproduces the committed table instead of quietly regenerating it into
 * whatever Unicode published most recently. Run `pnpm fmt` afterwards: the
 * pairs are written one per line and the formatter packs them.
 *
 * The wide set is East_Asian_Width of `W` or `F`, plus the blocks the data file
 * says unassigned code points default to `W` -- without those, a code point
 * Unicode has reserved for a CJK ideograph but not yet assigned would measure
 * one column instead of two.
 */

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

/** The Unicode version the committed table was generated from. */
const VERSION = '17.0.0';

const version = process.argv[2] ?? VERSION;
const URL = `https://www.unicode.org/Public/${version}/ucd/EastAsianWidth.txt`;
const OUT = join(
	dirname(fileURLToPath(import.meta.url)),
	'..',
	'src',
	'width',
	'east-asian-width.ts'
);

/**
 * The blocks whose unassigned code points default to `W`, as stated in the
 * header of `EastAsianWidth.txt`. They are listed there as prose, not as data,
 * so they have to be repeated here.
 */
const defaultWide = [
	[0x3400, 0x4dbf], // CJK Unified Ideographs Extension A
	[0x4e00, 0x9fff], // CJK Unified Ideographs
	[0xf900, 0xfaff], // CJK Compatibility Ideographs
	[0x20000, 0x2fffd], // Plane 2
	[0x30000, 0x3fffd], // Plane 3
];

const res = await fetch(URL);
if (!res.ok) {
	throw new Error(`Failed to fetch ${URL}: ${res.status} ${res.statusText}`);
}
const text = await res.text();

// read the version back out of the file rather than trusting the URL, so the
// generated header names what was actually parsed
const parsedVersion = /^#\s*EastAsianWidth-([\d.]+)\.txt/.exec(text)?.[1];
if (!parsedVersion) {
	throw new Error('Could not read the Unicode version from the data file');
}
if (parsedVersion !== version) {
	throw new Error(`Asked for Unicode ${version} but the data file says ${parsedVersion}`);
}

const ranges = [...defaultWide];

for (const line of text.split('\n')) {
	const data = line.split('#')[0].trim();
	if (!data) {
		continue;
	}

	const [codes, width] = data.split(';').map((part) => part.trim());
	if (width !== 'W' && width !== 'F') {
		continue;
	}

	const [start, end] = codes.split('..');
	ranges.push([Number.parseInt(start, 16), Number.parseInt(end ?? start, 16)]);
}

// sort and coalesce, so the lookup can binary search and so that the explicit
// ranges and the default blocks they sit inside collapse into one entry
ranges.sort((a, b) => a[0] - b[0]);

const merged = [];
for (const [start, end] of ranges) {
	const last = merged.at(-1);
	if (last && start <= last[1] + 1) {
		last[1] = Math.max(last[1], end);
	} else {
		merged.push([start, end]);
	}
}

// A 200 response is not a whole file. A truncated body parses fine, produces a
// handful of ranges, and would overwrite the table with something that measures
// most of CJK as one column -- so the result is checked before anything is
// written. The anchors are characters whose width is not going to change.
const anchors = [
	[0x1100, 'Hangul choseong kiyeok'],
	[0x3000, 'ideographic space'],
	[0x4e00, 'CJK unified ideograph'],
	[0xac00, 'Hangul syllable ga'],
	[0xf900, 'CJK compatibility ideograph'],
	[0xff01, 'fullwidth exclamation mark'],
	[0x1f600, 'grinning face'],
	[0x20000, 'plane 2'],
];

const covers = (cp) => merged.some(([start, end]) => cp >= start && cp <= end);

if (merged.length < 100) {
	throw new Error(`Only ${merged.length} ranges parsed; the data file looks truncated`);
}

for (const [cp, name] of anchors) {
	if (!covers(cp)) {
		throw new Error(`0x${cp.toString(16)} (${name}) is missing; the data file looks truncated`);
	}
}

for (const cp of [0x41, 0x20, 0x00e9]) {
	if (covers(cp)) {
		throw new Error(`0x${cp.toString(16)} should not be wide; the data file looks wrong`);
	}
}

const hex = (n) => `0x${n.toString(16)}`;
const pairs = merged.map(([start, end]) => `\t${hex(start)}, ${hex(end)},`).join('\n');

writeFileSync(
	OUT,
	`// Generated by scripts/generate-east-asian-width.mjs -- do not edit.
//
// Source: ${URL}
// Unicode ${parsedVersion}

/** The Unicode version the ranges below were generated from. */
export const unicodeVersion: string = '${parsedVersion}';

/**
 * Every code point whose East Asian Width is Wide or Fullwidth, as inclusive
 * \`[start, end]\` pairs flattened into one sorted array -- \`charWidth()\` binary
 * searches it, and a flat array of numbers is a third the size of an array of
 * pairs both in the source and on the heap.
 *
 * Ambiguous (\`A\`) is deliberately absent: it is two columns only in a legacy
 * East Asian context and one everywhere else, and one is the better default for
 * a CLI. Halfwidth and Narrow are one column, which is what everything not
 * listed here gets.
 */
export const wideRanges: readonly number[] = [
${pairs}
];
`
);

console.log(`Wrote ${merged.length} ranges from Unicode ${parsedVersion} to ${OUT}`);
console.log('Run `pnpm fmt` -- the formatter decides how many pairs fit on a line.');
