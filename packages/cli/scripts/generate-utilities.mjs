/**
 * Generates `packages/sigil/src/style/utilities.ts` from the property table.
 *
 * Run by hand, like `generate-east-asian-width.mjs`, and for the same reason:
 * the output is committed, so a regeneration that changes something is a diff
 * somebody reads rather than a step in a build nobody watches.
 *
 * ```
 * node scripts/generate-utilities.mjs   # from inside packages/cli
 * pnpm fmt
 * ```
 *
 * Why the generator is here and the output is over there: the generator reads
 * `PROPERTIES` and parses every declaration it writes, which is toolchain work
 * -- and a few hundred rules of CSS is a string constant, which is runtime
 * work. Splitting them that way is what `east-asian-width.ts` already does with
 * the Unicode tables, and it keeps the zero-dependency rule true of both halves:
 * the runtime gains a string, not a generator.
 *
 * It imports the generator's *source* rather than the built package, so this
 * needs `@ttylabs/sigil` built and nothing else -- the same thing
 * `pnpm --filter @ttylabs/cli dev` needs.
 *
 * **Variants are deliberately left out.** `md:flex-row` and its fifteen
 * siblings multiply the base set by the number of variants: 386 rules and 13 KB
 * become 4,996 rules and 215 KB, which is 7.29ms to parse against the base
 * set's 0.63ms -- a fifth of a CLI's whole startup, measured, for rules almost
 * no app uses. Shipping them whole is what SIG-81 (style shaking) has to make
 * affordable first; until then `generateUtilities()` still emits them for a
 * caller that wants the lot.
 */

import { generateUtilities, utilities } from '../src/utilities/index.ts';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', '..', 'sigil', 'src', 'style', 'utilities.ts');

const css = generateUtilities({ variants: false });
const count = utilities({ variants: false }).length;

const source = `// Generated by packages/cli/scripts/generate-utilities.mjs -- do not edit.
//
// Regenerate with \`node scripts/generate-utilities.mjs\` from inside
// packages/cli, then \`pnpm fmt\`. \`the committed utility sheet\` in
// packages/cli/test/utilities.test.ts fails if this file and the generator
// have come apart.

/**
 * The utility stylesheet: ${count} single-purpose classes over the property set.
 *
 * \`\`\`js
 * import { utilitySheet } from '@ttylabs/sigil/style';
 *
 * render(tree, { sheets: [utilitySheet()] });
 * \`\`\`
 *
 * It is ordinary CSS in the \`utilities\` layer, which is the last of the three
 * and is why a \`p-2\` beats an app's own \`.panel { padding: 4 }\` without a
 * specificity contest. Nothing in the runtime knows these rules are generated:
 * \`.p-2\` is a class selector like any other, matched by the same engine at the
 * same specificity.
 *
 * Opt-in rather than always on. It is ${(css.length / 1024).toFixed(1)} KB and 0.63ms to
 * parse, which is small but not nothing for a CLI that answers \`--version\` and
 * exits -- so an app that writes its own sheet pays neither.
 *
 * Variants (\`md:\`, \`focus:\`) are not here; see the generator for why.
 */
export const UTILITY_CSS: string = ${JSON.stringify(css)};
`;

writeFileSync(out, source);
process.stdout.write(`Wrote ${count} utilities to ${out}\n`);
