/**
 * Generates `packages/sigil/src/i18n/keys.ts` from the framework's own source.
 *
 * Run by hand, like `generate-utilities.mjs`, and for the same reason: the
 * output is committed, so a regeneration that changes something is a diff
 * somebody reads rather than a step in a build nobody watches.
 *
 * ```
 * node scripts/generate-sigil-keys.mjs   # from inside packages/cli
 * pnpm fmt
 * ```
 *
 * Why the generator is here and the output is over there: extracting the keys
 * means parsing every module, which needs oxc and is toolchain work, while what
 * the runtime gains is a sorted array of strings. That is the same split
 * `utilities.ts` and `east-asian-width.ts` already take, and it keeps the
 * zero-dependency rule true of both halves.
 *
 * Why it is committed in the *runtime* rather than kept in the toolchain:
 * `sigil check` compares an app's catalogs against the key set of the
 * `@ttylabs/sigil` that app actually depends on, and the toolchain is a
 * devDependency on its own version line -- so a copy here could be a release
 * ahead and report a missing key for a message the installed runtime does not
 * have. That is the argument the registry already records for shipping in the
 * runtime rather than the toolchain.
 *
 * The framework imports the tag by a relative specifier whose spelling depends
 * on how deep the module is, so the specifier is computed per file rather than
 * being one constant -- `importBindings()` matches the specifier exactly, which
 * is what makes it a binding rather than a spelling.
 */

import { keysIn } from '../src/build/i18n.ts';
import { parseModule, MODULE_RE } from '../src/build/parse-module.ts';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..', 'sigil', 'src');
const out = join(root, 'i18n', 'keys.ts');
const target = join(root, 'i18n', 'index.ts');

/** Every module under `src/`, the i18n module itself excluded. */
function* modules(dir) {
	for (const entry of readdirSync(dir, { withFileTypes: true }).sort((a, b) =>
		a.name < b.name ? -1 : 1
	)) {
		const path = join(dir, entry.name);

		if (entry.isDirectory()) {
			yield* modules(path);
		} else if (MODULE_RE.test(entry.name) && path !== target && path !== out) {
			yield path;
		}
	}
}

/**
 * The specifier a module imports the tag by, which is relative and so depends
 * on where the module sits.
 */
function specifierFrom(file) {
	const rel = relative(dirname(file), target).replaceAll('\\', '/').replace(/\.ts$/, '.js');

	return rel.startsWith('.') ? rel : `./${rel}`;
}

const strings = new Set();
const plurals = new Set();

for (const file of modules(root)) {
	const source = readFileSync(file, 'utf8');

	// a substring test first, so the overwhelming majority of modules are not
	// parsed at all -- the same filter the template pass takes, for its reason
	if (!source.includes('__`') && !source.includes('__n(')) {
		continue;
	}

	for (const found of keysIn(parseModule(file, source), { from: specifierFrom(file) })) {
		(found.kind === 'plural' ? plurals : strings).add(found.key);
	}
}

const sorted = [...new Set([...strings, ...plurals])].sort();
const sortedPlurals = [...plurals].sort();
const list = (values) => values.map((value) => `\t${JSON.stringify(value)},`).join('\n');

const source = `// Generated by packages/cli/scripts/generate-sigil-keys.mjs -- do not edit.
//
// Regenerate with \`node scripts/generate-sigil-keys.mjs\` from inside
// packages/cli, then \`pnpm fmt\`. \`the committed key set\` in
// packages/cli/test/i18n-keys.test.ts fails if this file and the source have
// come apart.

/**
 * Every message the framework itself can print, keyed on its English.
 *
 * ${sorted.length} keys, which is what a catalog has to carry to translate sigil's own
 * output whole. \`sigil check\` reads this to say which of them an app's
 * catalogs are missing -- and the other way round, so a reworded English
 * sentence shows up as one missing key and one orphan rather than as silence.
 *
 * It is a *generated* list rather than a hand-kept one for the reason every
 * other derived table here is: a second copy of the English that somebody has
 * to remember to edit is a copy that goes out of date, and the key is the
 * English, so there is nothing else for this to be.
 */
export const SIGIL_KEYS: readonly string[] = [
${list(sorted)}
];

/**
 * The ${sortedPlurals.length} of those whose catalog entry is an object of plural categories
 * rather than a string.
 *
 * A catalog may answer either -- a plain string is taken for a language with
 * one form for every count, which is what Japanese, Chinese and Korean have --
 * so this is what a catalog author needs to know rather than something the
 * lookup enforces.
 */
export const SIGIL_PLURAL_KEYS: readonly string[] = [
${list(sortedPlurals)}
];
`;

writeFileSync(out, source);
process.stdout.write(`Wrote ${sorted.length} keys (${sortedPlurals.length} plural) to ${out}\n`);
